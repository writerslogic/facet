// Generate wrangler.test.jsonc from the tracked wrangler.example.jsonc template.
//
// WHY this file differs from wrangler.jsonc: this miniflare version can't resolve the external AI
// worker, so the `ai` binding crashes the pool at startup; the ratelimit binding is likewise
// not provided by the test runtime. The NL pipeline is tested via an injectable stub LlmRunner and
// /api/stats/query returns 503 when env.AI is absent; the rate limiter is tested via a stub and the
// middleware no-ops when RATE_LIMITER is absent. Rather than hand-maintain a near-duplicate (drift
// risk), we strip the `ai` and `ratelimits` bindings and write a stable, formatted file.
// Kept git-tracked so CI reviews the generated output.
//
// Deterministic: parses the template (JSONC → JSON), deletes unsupported bindings, and pretty-prints
// with two-space indent and a fixed header. Running it unchanged produces an identical byte stream (no
// noisy diff). `pnpm --filter @facet/server pretest` runs this before every test run.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('..', import.meta.url));
const srcPath = `${dir}wrangler.example.jsonc`;
const outPath = `${dir}wrangler.test.jsonc`;

// Strip // line comments and /* */ block comments (none of ours are inside string literals), then
// drop trailing commas, so JSON.parse accepts the JSONC source.
function stripJsonc(text) {
	const noBlock = text.replace(/\/\*[\s\S]*?\*\//g, '');
	const noLine = noBlock.replace(/(^|[^:])\/\/.*$/gm, '$1');
	return noLine.replace(/,(\s*[}\]])/g, '$1');
}

const config = JSON.parse(stripJsonc(readFileSync(srcPath, 'utf8')));
delete config.ai;
delete config.ratelimits;
// Strip `queues` too: with no queue bound in tests, `env.INGEST_QUEUE` is undefined and the beacon takes
// its synchronous ingest fallback, so the collect suite asserts persistence directly (and the pool never
// has to stand up a queue consumer).
delete config.queues;
// Inject a test-only session secret so the account-auth routes are exercisable in tests (never a real
// secret; prod supplies SESSION_SECRET as a Worker secret, absent here).
config.vars = {
	...config.vars,
	SESSION_SECRET: 'test-session-secret',
	COLLECT_VALIDATE_SITE: 'false',
};
// Tests need no deployment identity: routes are never exercised in the pool, and D1 is local.
delete config.routes;
// Distinct id PER BINDING: miniflare keys its local databases by `database_id`, so reusing one string
// across two bindings would silently make CRM_DB an alias of DB and destroy the very isolation the
// separate-database design exists to provide. `DB` keeps its historical value so regenerating this
// tracked file produces no diff for the binding that already existed.
const TEST_DATABASE_IDS = { DB: 'test-database-id', CRM_DB: 'test-crm-database-id' };
for (const db of config.d1_databases ?? []) {
	db.database_id = TEST_DATABASE_IDS[db.binding] ?? `test-${db.binding.toLowerCase()}-database-id`;
}
// Bind CRM only in the test config so workerd can prove the engine-level schema guarantees. A
// self-hoster independently decides whether to provision and bind CRM_DB in their deployment.
if (!(config.d1_databases ?? []).some((db) => db.binding === 'CRM_DB')) {
	config.d1_databases = [
		...(config.d1_databases ?? []),
		{
			binding: 'CRM_DB',
			database_name: 'facet-crm',
			database_id: TEST_DATABASE_IDS.CRM_DB,
			migrations_dir: 'migrations-crm',
		},
	];
}

const header = [
	'// GENERATED by scripts/gen-test-wrangler.mjs from wrangler.example.jsonc — do not edit by hand.',
	'// Test-only Worker config: the template with `ai`, `ratelimits`, and `queues` bindings',
	'// stripped, because this miniflare version cannot provide them and crashes at startup. The NL',
	'// pipeline is tested via an injectable stub LlmRunner; the rate limiter via a stub with the',
	'// middleware no-opping when RATE_LIMITER is absent.',
	'// Deployment identity (`routes`, the real `database_id`) is stripped too, so this tracked file never',
	'// carries an operator\'s hostname or account identifiers. CRM_DB is injected only for engine-level',
	'// schema tests; its id differs from DB\'s so',
	'// miniflare keeps them separate. Regenerate: `pnpm --filter @facet/server pretest`.',
].join('\n');

writeFileSync(outPath, `${header}\n${JSON.stringify(config, null, 2)}\n`);
